// Package oscatdiff tests beebread's Go ports of the OSCAT libraries against
// beedance's evaluator running the OSCAT sources the ports follow: each
// function is called with the same arguments by both, and each function
// block is run through the same scans, and the results must agree.
//
// The sources are beebread's doc/beedance_*.st, read from the beebread
// module this module requires. A POU the cleaned sources comment out, which
// the evaluator cannot run, is left out.
//
// ports.go is generated by beebread:
//
//	go run ./tools/beedancegen -ports > ../beedance/oscatdiff/ports.go
//
// The module is its own so that beedance does not require beebread.
package oscatdiff

import "time"

// Block is the port of a function block.
type Block interface {
	INIT()
	Execute(now time.Time)
}
